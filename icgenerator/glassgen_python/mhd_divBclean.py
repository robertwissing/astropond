#!/usr/bin/env python
"""Static constrained hyperbolic divergence cleaning of a tipsy IC's B field.

Tricco & Price (2012, JCP 231) hyperbolic/parabolic cleaning in the
Tricco, Price & Bate (2016, JCP 322) energy-stable formulation, applied
STATICALLY: particle positions are frozen (v = 0, rho fixed), only (B, psi)
evolve, so the cleaning is a pure post/pre-processing pass usable on ANY
tipsy IC with a BField aux - e.g. an input snapshot BEFORE glassresample
reconstruction and/or the reconstructed output AFTER it.

    dB_a/dt  = -(grad psi)_a                    [SYMMETRIC/conjugate operator]
    dq_a/dt  = -c_a (div B)_a - q_a / tau_a     [DIFFERENCE operator]

with q = psi/c_h the evolved variable (the 2016 "constrained" choice: energy
stable under a spatially varying cleaning speed), per-particle cleaning speed
c_a = h_a (each kernel volume cleans on the same local crossing time, so one
global CFL step serves the whole h dynamic range) and tau_a = h_a/(sigma c_a)
= 1/sigma. The operator PAIR is the GDSPH (geometric density average) one of
Wissing & Shen (2020) - the glassgen 'gdforce' flavour, i.e. the SAME
discrete operators the target gasolinemhd code evolves, so the IC is clean
in the consumer's own measure. psi's source is the volume-weighted
difference divergence

    (div B)_a = sum_b (m_b/rho_b) (B_b - B_a) . gradWbar_ab

and B's update the gdforce symmetric gradient

    (grad psi)_a = rho_a sum_b m_b (psi_a + psi_b)/(rho_a rho_b) gradWbar_ab

with gradWbar_ab = 0.5 [gradW_ab(h_a) + gradW_ab(h_b)] in BOTH (the average
kernel makes each pair term antisymmetric under a<->b, which the energy
proof needs). These are exact negative adjoints under the volume inner
product sum_a (m_a/rho_a) u_a v_a, so the B <-> psi energy exchange is
conservative and the ONLY losses are the parabolic damping and the
(removed) divergence energy - cleaning strictly dissipates. Constant B is
an EXACT fixed point (difference operator kills it, psi stays 0), including
at open boundaries with one-sided kernels.

Formally the induction side is the d(B/rho)/dt equation of the SPMHD
scheme; with frozen particles (drho/dt = 0, div v = 0) it reduces exactly
to dB_a/dt = -(grad psi)_a and the (psi/2) div v term in dpsi/dt vanishes,
which is what is implemented. A future moving-particle extension must
restore both rho factors and that term.

Time integration is a STAGGERED leapfrog (no Euler): q lives at half steps,
B at integer steps, damping applied as the exact exponential factor
exp(-sigma dt) (Tricco's recommendation), dt = --dt in units of the local
kernel crossing time (stable well below ~0.3).

Both operators are members of the glassgen.flavours operator family
(diff_divergence / sym_gradient), which is also where the flavour-matched
diff_curl used to build B = curl A lives - so an IC generated by
IC_setBField.py and cleaned here uses one discrete operator family end to end.

SPH conventions reused from glassgen (the glassrelax machinery): Wendland C2
kernel, kNN smoothing lengths (support 2h), NeighborList candidate lists +
transpose for the scatter side, particle_density for (rho, h) - i.e. the
same estimate the relax itself uses. No grad-h Omega terms (glassgen
convention). NB the sph_interp validation diagnostics measure divergence
with a cubic-spline difference operator: cleaning zeroes ITS OWN operator's
divergence, the cross-kernel readout retains a small floor.

Output: a copy of the snapshot named OUT, OUT.BField (cleaned, same packed
layout/length as the input aux), all other sibling aux files copied
alongside (drop-in replacement IC), and a human-readable OUT_divclean.txt
audit with the configuration and convergence trace (unless ``--no-audit``).
Gas only (B is a gas field); dark/star untouched.

Usually run through its wrapper, which sets SETUP/PYTHONPATH itself:

  bin/divbclean IN.00000 [-o OUT.00000] \
      [--box L [LY LZ] | --open] [--sigma 1.0] [--dt 0.2] [--steps 500]

or directly:

  export SETUP=<repo>/setupfiles           # readtipsy etc.
  PYTHONPATH=. python mhd_divBclean.py IN.00000 [-o OUT.00000] \
      [--box L [LY LZ] | --open] [--sigma 1.0] [--dt 0.2] [--steps 500]
"""
import argparse
import glob
import math
import os
import re
import shutil
import sys
import time

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
# The operator PAIR: the difference divergence psi is sourced from and the
# symmetric gradient B is updated with, both from the flavour registry so the
# exchange is the exact-adjoint (energy-conserving) one. `_div_b`/`_grad_psi`
# keep their local names as the historical spelling of these two members.
from glassgen.flavours import (FLAVOUR_SPECS,  # noqa: E402
                               diff_divergence as _div_b,
                               divergence_error,
                               flavour_spec,
                               sym_gradient as _grad_psi)


def clean_divergence(pos, mass, B, box=None, nsmooth=64, sigma=1.0,
                     dt=0.2, steps=500, every=25, tol=0.0, rho=None, h=None,
                     flavour='gdforce', verbose=False,
                     target_mean=0.0, target_max=0.0):
    """Statically clean div B on frozen particles. Returns (B_clean, audit).

    pos, mass : (N,3), (N) gas particles (FROZEN - never moved).
    B         : (N,3) magnetic field to clean (input untouched; copy evolved).
    box       : (3,) periodic box lengths, or None for an open domain.
    sigma     : parabolic damping (tau = 1/sigma local crossing times);
                Tricco & Price's recommended ~1.0 in 3D.
    dt        : staggered step in local-crossing-time units (c_a = h_a).
    steps     : leapfrog steps (the budget/upper bound). every : trace cadence.
    tol       : if > 0, stop early when the mean dimensionless divergence
                improves by < tol (relative) over an audit interval (a
                convergence-stall guard, not an absolute target).
    target_mean : if > 0, stop once the MEAN dimensionless divergence error
                divBerr = h|divB|/|B| drops to <= target_mean.
    target_max  : if > 0, stop once the MAX divBerr drops to <= target_max.
                When both targets are set, BOTH must be met to stop.
    rho, h    : optional precomputed glassgen density/smoothing length.
    flavour   : SPH operator flavour from glassgen.flavours.FLAVOURS
                ('gdforce' default = the gasolinemhd convention); BOTH
                operators (symmetric gradient + its energy-conjugate
                difference divergence) derive from the registry entry.
    """
    from glassgen.flavours import operator_state

    iflav, ikmode = flavour_spec(flavour)
    pos = np.ascontiguousarray(pos, dtype=np.float64)
    mass = np.ascontiguousarray(mass, dtype=np.float64)
    B = np.array(B, dtype=np.float64, copy=True)
    n = len(mass)
    if pos.shape != (n, 3) or B.shape != (n, 3):
        raise ValueError('pos and B must have shape (N, 3)')
    periodic = box is not None

    # one frozen-configuration workspace (rho, h, candidate list + transpose)
    # shared by every operator call in the loop below
    st = operator_state(pos, mass, box=box, nsmooth=nsmooth, rho=rho, h=h)
    rho, h, boxarr = st.rho, st.h, st.box
    idx, rev_indptr, rev_indices = st.idx, st.rev_indptr, st.rev_indices

    ch = h                                   # c_a = h_a: uniform local CFL
    damp = math.exp(-sigma * dt)
    vol = mass / rho
    divB = np.empty(n)
    grad = np.empty((n, 3))
    mean_b0 = np.mean(B, axis=0)

    def eps_stats(d):
        e = divergence_error(B, d, h)
        return (float(e.mean()), float(np.percentile(e, 95)),
                float(e.max()), float(e.min()))

    def energies(q):
        eb = 0.5 * float(np.sum(vol * np.sum(B * B, axis=1)))
        ep = 0.5 * float(np.sum(vol * q * q))
        return eb, ep

    _div_b(pos, mass, rho, h, B, iflav, ikmode, idx, rev_indptr,
           rev_indices, boxarr, periodic, divB)
    trace = dict(step=[], eps_mean=[], eps_p95=[], eps_max=[], eps_min=[],
                 e_b=[], e_psi=[])
    e_b0, _ = energies(np.zeros(n))

    def _progress(it, m, x, mn, e_b, tsec):
        e_clean = e_b0 - e_b
        loss = e_clean / e_b0 if e_b0 > 0.0 else 0.0
        print(f'  it {it:6d}  divBerr[mean/max/min] {m:.4e}/{x:.4e}/{mn:.4e}'
              f'  Emag {e_b:.6e}  EClean {e_clean:.4e}  Emag_loss {loss:+.3%}'
              f'  ({tsec:.0f}s)', flush=True)

    m0, p0, x0, n0 = eps_stats(divB)
    trace['step'].append(0)
    trace['eps_mean'].append(m0)
    trace['eps_p95'].append(p0)
    trace['eps_max'].append(x0)
    trace['eps_min'].append(n0)
    trace['e_b'].append(e_b0)
    trace['e_psi'].append(0.0)
    if verbose:
        _progress(0, m0, x0, n0, e_b0, 0.0)

    q = -0.5 * dt * ch * divB               # staggered start: q at t = dt/2
    last_mean = m0
    t0 = time.perf_counter()
    for it in range(1, steps + 1):
        psi = ch * q
        _grad_psi(pos, mass, rho, h, psi, iflav, ikmode, idx, rev_indptr,
                  rev_indices, boxarr, periodic, grad)
        B -= dt * grad
        _div_b(pos, mass, rho, h, B, iflav, ikmode, idx, rev_indptr,
           rev_indices, boxarr, periodic, divB)
        q = q * damp - dt * ch * divB
        if it % every == 0 or it == steps:
            m, p, x, mn = eps_stats(divB)
            e_b, e_p = energies(q)
            trace['step'].append(it)
            trace['eps_mean'].append(m)
            trace['eps_p95'].append(p)
            trace['eps_max'].append(x)
            trace['eps_min'].append(mn)
            trace['e_b'].append(e_b)
            trace['e_psi'].append(e_p)
            if verbose:
                _progress(it, m, x, mn, e_b, time.perf_counter() - t0)
            # absolute divergence targets (both must be met when both set)
            if (target_mean > 0.0 or target_max > 0.0) \
                    and (target_mean <= 0.0 or m <= target_mean) \
                    and (target_max <= 0.0 or x <= target_max):
                if verbose:
                    met = []
                    if target_mean > 0.0:
                        met.append(f'mean<={target_mean:g}')
                    if target_max > 0.0:
                        met.append(f'max<={target_max:g}')
                    print(f'  reached divBerr target ({", ".join(met)}) '
                          f'at step {it}', flush=True)
                break
            # relative convergence-stall guard
            if tol > 0.0 and last_mean > 0.0 \
                    and (last_mean - m) / last_mean < tol:
                break
            last_mean = m

    reached = ((target_mean > 0.0 or target_max > 0.0)
               and (target_mean <= 0.0 or trace['eps_mean'][-1] <= target_mean)
               and (target_max <= 0.0 or trace['eps_max'][-1] <= target_max))
    audit = dict(steps=int(trace['step'][-1]), steps_budget=int(steps),
                 every=int(every), tol=float(tol), sigma=sigma, dt=dt,
                 nsmooth=nsmooth, periodic=periodic, flavour=flavour,
                 eps_before=(m0, p0, x0),
                 eps_after=(trace['eps_mean'][-1], trace['eps_p95'][-1],
                            trace['eps_max'][-1]),
                 eps_min_before=n0, eps_min_after=trace['eps_min'][-1],
                 target_mean=target_mean, target_max=target_max,
                 target_reached=bool(reached),
                 e_b_before=e_b0, e_b_after=trace['e_b'][-1],
                 e_psi_after=trace['e_psi'][-1],
                 mean_b_shift=np.mean(B, axis=0) - mean_b0,
                 trace={k: np.asarray(v) for k, v in trace.items()})
    return B, audit


def _cleaning_plan(steps, target_mean=0.0, target_max=0.0, tol=0.0):
    """One-line user-facing description of the iteration budget/stops."""
    targets = []
    if target_mean > 0.0:
        targets.append(f'mean <= {target_mean:g}')
    if target_max > 0.0:
        targets.append(f'max <= {target_max:g}')

    if targets:
        message = (f'cleaning plan: up to {steps} iterations; target divBerr '
                   + ' and '.join(targets))
        if len(targets) > 1:
            message += ' (both required)'
    elif tol > 0.0:
        message = (f'cleaning plan: up to {steps} iterations; no absolute '
                   f'divBerr target')
    else:
        message = f'cleaning plan: {steps} iterations (no divBerr target)'

    if tol > 0.0:
        message += f'; stall tolerance {tol:g} per audit interval'
    return message


def _write_audit_text(path, audit, infile, outfile, box):
    """Write a self-describing, human-readable cleaning trace."""
    trace = audit['trace']
    step = np.asarray(trace['step'])
    emag = np.asarray(trace['e_b'])
    epsi = np.asarray(trace['e_psi'])
    eclean = audit['e_b_before'] - emag
    if audit['e_b_before'] > 0.0:
        emag_loss = eclean / audit['e_b_before']
    else:
        emag_loss = np.zeros_like(eclean)
    table = np.column_stack((
        step, trace['eps_mean'], trace['eps_p95'], trace['eps_max'],
        trace['eps_min'], emag, epsi, eclean, emag_loss))

    if box is None:
        domain = 'open'
    else:
        domain = 'periodic box ' + ' '.join(f'{x:.16g}' for x in np.asarray(box))
    target_mean = audit['target_mean']
    target_max = audit['target_max']
    target_requested = target_mean > 0.0 or target_max > 0.0
    header = '\n'.join([
        'divbclean audit',
        f'input: {infile}',
        f'output: {outfile}',
        f'domain: {domain}',
        f'SPH flavour: {audit["flavour"]}',
        f'nsmooth: {audit["nsmooth"]}',
        f'sigma: {audit["sigma"]:.16g}',
        f'dt: {audit["dt"]:.16g}',
        f'iteration budget: {audit["steps_budget"]}',
        f'iterations completed: {audit["steps"]}',
        f'audit interval: {audit["every"]}',
        f'stall tolerance: {audit["tol"]:.16g}',
        ('target divBerr mean: disabled' if target_mean <= 0.0
         else f'target divBerr mean: {target_mean:.16g}'),
        ('target divBerr max: disabled' if target_max <= 0.0
         else f'target divBerr max: {target_max:.16g}'),
        ('target reached: not requested' if not target_requested
         else f'target reached: {str(bool(audit["target_reached"])).lower()}'),
        'divBerr definition: h*abs(divB)/max(|B|,1e-12*Brms)',
        'EClean = Emag(iteration 0) - Emag',
        'Emag_loss = EClean / Emag(iteration 0)',
        'columns: iteration divBerr_mean divBerr_p95 divBerr_max divBerr_min '
        'Emag Epsi EClean Emag_loss',
    ])
    np.savetxt(path, table,
               fmt=['%d'] + ['%.16e'] * (table.shape[1] - 1),
               header=header, comments='# ')


def main(argv=None):
    ap = argparse.ArgumentParser(
        prog=os.environ.get('IC_TOOL_NAME'),   # set by the bin/ wrapper
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('infile', help='input tipsy snapshot (with .BField aux)')
    ap.add_argument('-o', dest='out', default=None,
                    help='output snapshot path (default: infile with _Bclean '
                         'inserted before the .NNNNN extension)')
    grp = ap.add_mutually_exclusive_group()
    grp.add_argument('--box', type=float, nargs='+', metavar='L',
                     help='periodic box lengths (one value or LX LY LZ)')
    grp.add_argument('--open', action='store_true',
                     help='open (non-periodic) domain')
    ap.add_argument('-s', dest='nsmooth', type=int, default=64)
    ap.add_argument('--flavour', default='gdforce',
                    choices=sorted(FLAVOUR_SPECS),
                    help='SPH operator flavour (glassgen.flavours registry; '
                         'gdforce = the gasolinemhd GDSPH convention, '
                         'default)')
    ap.add_argument('--sigma', type=float, default=1.0,
                    help='parabolic damping strength (default 1.0)')
    ap.add_argument('--dt', type=float, default=0.2,
                    help='staggered step in local kernel-crossing units '
                         '(default 0.2; stability requires well below ~0.3)')
    ap.add_argument('--steps', type=int, default=500,
                    help='leapfrog steps (default 500)')
    ap.add_argument('--every', type=int, default=25,
                    help='audit/print cadence (default 25)')
    ap.add_argument('--tol', type=float, default=0.0,
                    help='early stop when mean divBerr improves < tol relative '
                         'per audit interval (0 = run the full budget)')
    ap.add_argument('--target-mean', type=float, default=0.0,
                    help='stop once the MEAN dimensionless divergence error '
                         'h|divB|/max(|B|,1e-12 Brms) drops to <= this value '
                         '(0 = disabled)')
    ap.add_argument('--target-max', type=float, default=0.0,
                    help='stop once the MAX h|divB|/max(|B|,1e-12 Brms) drops '
                         'to <= this value (0 = disabled); with --target-mean '
                         'BOTH must be met')
    ap.add_argument('--no-copy-aux', dest='copy_aux', action='store_false',
                    help='write only OUT and OUT.BField (skip copying the '
                         'other sibling aux files)')
    ap.add_argument('--no-audit', action='store_true',
                    help='do not write the OUT_divclean.txt convergence audit')
    args = ap.parse_args(argv)

    sys.path.insert(0, os.environ.get('SETUP', os.path.join(
        os.path.dirname(os.path.abspath(__file__)), '..', '..', 'setupfiles')))
    import readtipsy as tip

    def _aux_flat(path):
        """Tipsy aux payload (big-endian f4 after the i4 count) or None."""
        if not os.path.isfile(path):
            return None
        with open(path, 'rb') as f:
            np.fromfile(f, dtype=np.dtype('>i4'), count=1)
            return np.fromfile(f, dtype=np.dtype('>f4')).astype(np.float64)

    def read_vector_aux(snap, label, n):
        arr = _aux_flat(snap + '.' + label)
        if arr is not None and arr.size >= 3 * n:
            return arr[:3 * n].reshape(n, 3)
        comps = [_aux_flat(snap + '.' + label + c) for c in 'xyz']
        if any(c is None for c in comps):
            return None
        return np.stack([c[:n] for c in comps], axis=1)

    out = args.out
    if out is None:
        out = (re.sub(r'(\.\d+)$', r'_Bclean\1', args.infile)
               if re.search(r'\.\d+$', args.infile)
               else args.infile + '_Bclean')
    if os.path.abspath(out) == os.path.abspath(args.infile):
        ap.error('output would overwrite the input snapshot')

    gas, _, _, hdr, _ = tip.readtipsy(args.infile)
    ngas = len(gas)
    if ngas == 0:
        sys.exit('no gas particles - nothing to clean')
    pos = np.asarray(gas[:, 1:4], dtype=np.float64)
    mass = np.asarray(gas[:, 0], dtype=np.float64)
    B = read_vector_aux(args.infile, 'BField', ngas)
    if B is None:
        sys.exit(f'{args.infile}.BField aux not found')
    print(f'read {ngas} gas from {args.infile}; '
          f'|B| mean {np.mean(np.linalg.norm(B, axis=1)):.6e}', flush=True)

    if args.box is not None:
        box = (np.repeat(args.box[0], 3) if len(args.box) == 1
               else np.asarray(args.box, dtype=np.float64))
        if box.shape != (3,):
            ap.error('--box takes one length or LX LY LZ')
        print(f'periodic box {box}', flush=True)
    elif args.open:
        box = None
        print('open domain', flush=True)
    else:
        box = None
        param = re.sub(r'\.\d+$', '', args.infile) + '.param'
        if os.path.isfile(param):
            sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
            from glassgen.params import box_from_param, read_param
            box = box_from_param(read_param(param))
        print(f'domain from sibling .param: '
              f'{"open" if box is None else box}', flush=True)

    print(_cleaning_plan(args.steps, args.target_mean, args.target_max, args.tol),
          flush=True)
    t0 = time.perf_counter()
    B_clean, audit = clean_divergence(
        pos, mass, B, box=box, nsmooth=args.nsmooth, sigma=args.sigma,
        dt=args.dt, steps=args.steps, every=args.every, tol=args.tol,
        flavour=args.flavour, verbose=True,
        target_mean=args.target_mean, target_max=args.target_max)
    if (args.target_mean > 0.0 or args.target_max > 0.0) \
            and not audit['target_reached']:
        print(f'WARNING: divBerr target not reached within {args.steps} steps '
              f'(raise --steps)', flush=True)
    m0, p0, x0 = audit['eps_before']
    m1, p1, x1 = audit['eps_after']
    de = audit['e_b_after'] / audit['e_b_before'] - 1.0
    print(f'cleaned in {audit["steps"]} steps ({time.perf_counter()-t0:.0f}s): '
          f'divBerr mean {m0:.3e} -> {m1:.3e} '
          f'(x{m0/max(m1,1e-300):.1f} down), '
          f'p95 {p0:.3e} -> {p1:.3e}, max {x0:.3e} -> {x1:.3e}; '
          f'E_B {de:+.3%}, residual E_psi/E_B '
          f'{audit["e_psi_after"]/audit["e_b_after"]:.2e}', flush=True)

    shutil.copyfile(args.infile, out)
    packed = args.infile + '.BField'
    if os.path.isfile(packed):
        # preserve the original packing: replace the first 3*ngas entries
        flat = np.array(np.fromfile(packed, dtype=np.dtype('>f4'), offset=4),
                        dtype=np.float64)
        flat[:3 * ngas] = B_clean.ravel()
    else:                                    # component-file input: write packed
        flat = B_clean.ravel()
    # vector writer: header = number of PARTICLES (len/3), x,y,z interleaved.
    # The scalar writetipsyaux wrote len(flat) = 3N as the header, which
    # ChaNGa's arrayFileExists rejects (header must equal nTotalParticles);
    # with CkAssert compiled out it then parses the binary as ASCII and
    # silently loads garbage into B.
    tip.writetipsyVecaux(flat.reshape(-1, 3), 'BField', out)
    wrote = [f'{out}.BField ({len(flat)} values)']
    # component-file twins (BFieldx/y/z) are a second, independent copy of the
    # field that some consumers read INSTEAD of the packed file - every B
    # representation present on the input must be replaced with the cleaned
    # values or a consumer silently reads the dirty field.
    # Like the packed file above, each twin must keep the INPUT's length and
    # have only its gas rows replaced. Writing B_clean (gas only) directly
    # truncated the twin to ngas rows on any snapshot with dark/star, leaving
    # .BField at N and .BFieldx at ngas - inconsistent, and short by exactly
    # the dark+star block a consumer expects to index past.
    for i, c in enumerate('xyz'):
        cpath = args.infile + '.BField' + c
        if os.path.isfile(cpath):
            comp = _aux_flat(cpath)
            if comp is None or len(comp) < ngas:
                comp = B_clean[:, i]
            else:
                comp[:ngas] = B_clean[:, i]
            tip.writetipsyaux(comp, 'BField' + c, out)
            wrote.append(f'{out}.BField{c} ({len(comp)} values)')
    print('wrote ' + out + ' + ' + ', '.join(wrote), flush=True)
    if args.copy_aux:
        copied = 0
        for aux in glob.glob(args.infile + '.*'):
            label = aux[len(args.infile) + 1:]
            if not label or '/' in label or label.startswith('BField'):
                continue
            shutil.copyfile(aux, out + '.' + label)
            copied += 1
        if copied:
            print(f'copied {copied} sibling aux files', flush=True)
    if not args.no_audit:
        audit_path = out + '_divclean.txt'
        _write_audit_text(audit_path, audit, args.infile, out, box)
        print(f'audit: {audit_path}', flush=True)


if __name__ == '__main__':
    main()
