#!/usr/bin/env python
"""Convert a gasoline/tipsy IC into an OpenGadget3 IC (GADGET type-0 HDF5) + param.

OpenGadget3 is a Gadget-family TreeSPH/SPMHD particle code: the IC is a 1:1 copy of
the SPH particles, NOT an SPH->grid interpolation. The GADGET type-0 HDF5 it reads
(ICFormat 3) is exactly what the AREPO/GIZMO export writer produces (identical
PartType0 dataset names), so the IC HDF5 is generated by the shared
`particles_to_arepo` path (--voronoi-particles, --output-format arepo). The only
OpenGadget3-specific artefact is the run parameterfile, written here from the
gasoline `.param`.

    ICconvert_tipsytoopengadget3.py <input> <output> [--param-out P]
                                    [--output-dir D] [--boxsize L] [--mhd]

  input    tipsy snapshot (e.g. datafiles/run.00000).
  output   OpenGadget3 IC HDF5 path (e.g. datafiles/run_opengadget3.hdf5).

Options: --fields (default rho,vx,vy,vz,Bx,By,Bz), --tu-fac (override dTuFac),
--param-out (also write an OpenGadget3 parameterfile here), --output-dir
(OutputDir in that file), --boxsize (X period). MHD (the magnetic parameter
block) is AUTO-DETECTED from a nonzero BField aux so the converter works
standalone; --mhd/--no-mhd force it.
"""
import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from IC_interpolate_to_grid import main as interp_main
from sph_interp._opengadget3.opengadget3_param import write_run_param
from sph_interp.export import scale_hdf5_bfield, MU0_CODE_TO_GAUSS
from ICconvert_common import (find_sibling_param, gadget_particle_argv,
                              has_nonzero_b)




def build_argv(args):
    return gadget_particle_argv(args)


def parse(argv=None):
    pa = argparse.ArgumentParser(
        prog="ICconvert_tipsytoopengadget3",
        description="tipsy -> OpenGadget3 IC (GADGET HDF5, particle copy) + param.")
    pa.add_argument("input", help="tipsy snapshot")
    pa.add_argument("output", help="OpenGadget3 IC HDF5 path")
    pa.add_argument("--fields", default="rho,vx,vy,vz,Bx,By,Bz")
    pa.add_argument("--tu-fac", type=float, default=None)
    pa.add_argument("--mhd", dest="mhd", action="store_const", const=True,
                    default=None,
                    help="emit the magnetic parameter block (IC carries B). "
                         "Default: auto-detect from a nonzero BField aux.")
    pa.add_argument("--no-mhd", dest="mhd", action="store_const", const=False,
                    help="force hydro (skip the magnetic block) even if B is present.")
    pa.add_argument("--param-out", default=None,
                    help="also write an OpenGadget3 parameterfile here, run params "
                         "from the gasoline .param beside INPUT")
    pa.add_argument("--output-dir", default=None,
                    help="OpenGadget3 OutputDir written into the parameterfile "
                         "(default: '<param-out dir>/output/')")
    pa.add_argument("--boxsize", type=float, default=None,
                    help="override BoxSize (default: dxPeriod; X period). Non-cubic "
                         "y/z need OpenGadget3 compiled with LONG_Y/LONG_Z.")
    return pa.parse_args(argv)


def write_param(args):
    if not args.param_out:
        return
    gas_param = find_sibling_param(args.input)
    if gas_param is None:
        print("WARNING: no gasoline .param beside %r; cannot write parameterfile."
              % args.input)
        return
    init_cond = os.path.splitext(args.output)[0]   # ICFormat 3 -> no extension
    output_dir = args.output_dir
    if output_dir is None:
        output_dir = (os.path.dirname(os.path.abspath(args.param_out)) or ".") \
            + os.sep + "output" + os.sep
    # MHD auto-detected from the IC (nonzero BField aux) unless forced via
    # --mhd/--no-mhd, so the converter is correct when run standalone.
    mhd = args.mhd if args.mhd is not None else has_nonzero_b(args.input)
    write_run_param(gas_param, args.param_out, init_cond, output_dir,
                    boxsize=args.boxsize, mhd=mhd)
    print("Wrote OpenGadget3 parameterfile -> %s (run params from %s)"
          % (args.param_out, gas_param))


if __name__ == "__main__":
    args = parse()
    interp_main(build_argv(args))
    # OpenGadget3 runs in Gaussian B units like GIZMO/AREPO (no MU0_UNITY): mu0_inv
    # = 1/4pi, so a mu0=1 field fed 1:1 is 4pi too weak in pressure. Convert the
    # mu0=1 tipsy B to Gauss (x sqrt(4pi)) for consistency with the other two Gadget
    # codes; the reverse converter divides it back. No-op for hydro ICs.
    if scale_hdf5_bfield(args.output, MU0_CODE_TO_GAUSS):
        print("Scaled IC MagneticField by sqrt(4pi)=%.6f (mu0=1 code -> Gadget Gauss)"
              % MU0_CODE_TO_GAUSS)
    write_param(args)
