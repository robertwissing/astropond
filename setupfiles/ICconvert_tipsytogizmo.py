#!/usr/bin/env python
"""Convert a gasoline/tipsy IC into a GIZMO IC (GADGET type-0 HDF5) + parameterfile.

GIZMO is a particle code (meshless finite-mass / SPH / MHD): the IC is a 1:1 copy
of the SPH particles, NOT an SPH->grid interpolation. The GADGET type-0 HDF5 it
reads (ICFormat 3) is exactly what the AREPO export writer produces, so the IC
HDF5 is generated by the shared `particles_to_arepo` path (--voronoi-particles,
--output-format arepo). The only GIZMO-specific artefact is the run
parameterfile, written here from the gasoline `.param`.

    ICconvert_tipsytogizmo.py <input> <output> [--param-out P] [--output-dir D]
                              [--boxsize L] [--mhd]

  input    tipsy snapshot (e.g. datafiles/run.00000).
  output   GIZMO IC HDF5 path (e.g. datafiles/run_gizmo.hdf5).

Options: --fields (default rho,vx,vy,vz,Bx,By,Bz), --tu-fac (override dTuFac),
--param-out (also write a GIZMO parameterfile here), --output-dir (GIZMO OutputDir
in that file), --boxsize (X period). MHD (seed BiniX/Y/Z) is AUTO-DETECTED from a
nonzero BField aux so the converter works standalone; --mhd/--no-mhd force it.
"""
import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from IC_interpolate_to_grid import main as interp_main
from sph_interp._gizmo.gizmo_param import write_run_param
from sph_interp.export import scale_hdf5_bfield, MU0_CODE_TO_GAUSS
from ICconvert_common import has_nonzero_b


def _boxsize_from_ic(hdf5_path):
    """Read BoxSize from a just-written GADGET/AREPO IC header, so the GIZMO
    parameterfile's BoxSize matches the framed particle extent for non-periodic
    (isolated) ICs. Returns None if it can't be read (write_run_param then falls
    back to the .param dxPeriod)."""
    try:
        import h5py
        with h5py.File(hdf5_path, "r") as f:
            return float(f["Header"].attrs["BoxSize"])
    except Exception as e:
        print("WARNING: could not read BoxSize from %r (%s); "
              "parameterfile BoxSize falls back to the .param." % (hdf5_path, e))
        return None


def _find_gasoline_param(tipsy_input):
    base = tipsy_input
    if "." in os.path.basename(base):
        base = base.rsplit(".", 1)[0]
    cand = base + ".param"
    return cand if os.path.exists(cand) else None


def build_argv(args):
    # 1:1 particle copy -> GADGET type-0 HDF5 (the GIZMO IC). The "arepo" output
    # format is the GADGET writer; --voronoi-particles selects the copy path.
    argv = [args.input, args.output, "--output-format", "arepo",
            "--voronoi-particles", "--fields", args.fields]
    if args.tu_fac is not None:
        argv += ["--tu-fac", str(args.tu_fac)]
    return argv


def parse(argv=None):
    pa = argparse.ArgumentParser(
        prog="ICconvert_tipsytogizmo",
        description="tipsy -> GIZMO IC (GADGET HDF5, particle copy) + parameterfile.")
    pa.add_argument("input", help="tipsy snapshot")
    pa.add_argument("output", help="GIZMO IC HDF5 path")
    pa.add_argument("--fields", default="rho,vx,vy,vz,Bx,By,Bz")
    pa.add_argument("--tu-fac", type=float, default=None)
    pa.add_argument("--mhd", dest="mhd", action="store_const", const=True,
                    default=None,
                    help="seed BiniX/Y/Z in the parameterfile (IC carries B). "
                         "Default: auto-detect from a nonzero BField aux.")
    pa.add_argument("--no-mhd", dest="mhd", action="store_const", const=False,
                    help="force hydro (skip the BiniX/Y/Z seed) even if B is present.")
    pa.add_argument("--grav", dest="grav", action="store_const", const=True,
                    default=None,
                    help="self-gravity run: GravityConstantInternal=1.0 (G in code "
                         "units) + gas softening floor; needs the GIZMO_grav binary. "
                         "Default: auto-detect from bDoGravity in the gasoline .param.")
    pa.add_argument("--param-out", default=None,
                    help="also write a GIZMO parameterfile here, run params from "
                         "the gasoline .param beside INPUT")
    pa.add_argument("--output-dir", default=None,
                    help="GIZMO OutputDir written into the parameterfile "
                         "(default: '<param-out dir>/output/')")
    pa.add_argument("--boxsize", type=float, default=None,
                    help="override BoxSize (default: dxPeriod; X period). Non-cubic "
                         "y/z need GIZMO compiled with BOX_LONG_Y/BOX_LONG_Z.")
    return pa.parse_args(argv)


def write_param(args):
    if not args.param_out:
        return
    gas_param = _find_gasoline_param(args.input)
    if gas_param is None:
        print("WARNING: no gasoline .param beside %r; cannot write parameterfile."
              % args.input)
        return
    init_cond = os.path.splitext(args.output)[0]   # ICFormat 3 -> no extension
    output_dir = args.output_dir
    if output_dir is None:
        output_dir = (os.path.dirname(os.path.abspath(args.param_out)) or ".") \
            + os.sep + "output" + os.sep
    # BoxSize must match the IC the writer just produced. For a non-periodic IC
    # (no dxPeriod in the .param) the writer frames coords to the particle extent
    # and stores that BoxSize in the HDF5 Header; read it back so the param agrees
    # (else it would default to 1.0 and leave particles outside the box).
    boxsize = args.boxsize
    if boxsize is None:
        boxsize = _boxsize_from_ic(args.output)
    # MHD auto-detected from the IC (nonzero BField aux) unless forced via
    # --mhd/--no-mhd, so the converter is correct when run standalone.
    mhd = args.mhd if args.mhd is not None else has_nonzero_b(args.input)
    write_run_param(gas_param, args.param_out, init_cond, output_dir,
                    boxsize=boxsize, mhd=mhd, grav=args.grav)
    print("Wrote GIZMO parameterfile -> %s (run params from %s)"
          % (args.param_out, gas_param))


if __name__ == "__main__":
    args = parse()
    interp_main(build_argv(args))
    # GIZMO reads the IC MagneticField as GAUSS (init.c: B *= UnitMagneticField_in_gauss
    # / UNIT_B_IN_GAUSS = 1/sqrt(4pi) for code units = 1) -> convert the mu0=1 tipsy B
    # to Gauss so the internal field matches gasoline. No-op for hydro ICs.
    if scale_hdf5_bfield(args.output, MU0_CODE_TO_GAUSS):
        print("Scaled IC MagneticField by sqrt(4pi)=%.6f (mu0=1 code -> GIZMO Gauss)"
              % MU0_CODE_TO_GAUSS)
    write_param(args)
